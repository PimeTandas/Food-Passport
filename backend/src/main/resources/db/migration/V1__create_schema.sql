-- Flyway runs each V<n>__*.sql file once, in order, and records it.
-- Never edit a migration that has already run: add a new V<n+1> file instead.

CREATE TABLE app_user (                       -- "user" is a reserved word in SQL
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    username      VARCHAR(30)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE friendship (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    addressee_id BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    status       VARCHAR(10) NOT NULL,         -- PENDING or ACCEPTED
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT friendship_pair_unique UNIQUE (requester_id, addressee_id),
    CONSTRAINT friendship_not_self CHECK (requester_id <> addressee_id)
);

CREATE TABLE country (
    code      VARCHAR(2)   PRIMARY KEY,        -- ISO 3166-1 alpha-2, e.g. 'JP'
    name      VARCHAR(100) NOT NULL,
    continent VARCHAR(20)  NOT NULL,
    flag      VARCHAR(8)   NOT NULL
);

-- The shared food event: what was eaten, where, and how much it cost.
CREATE TABLE food_entry (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code   VARCHAR(2)    NOT NULL REFERENCES country (code),
    created_by_id  BIGINT       REFERENCES app_user (id) ON DELETE SET NULL,
    dish_name      VARCHAR(200) NOT NULL,
    place_name     VARCHAR(200),
    homemade       BOOLEAN      NOT NULL,
    price_amount   NUMERIC(12, 2),
    price_currency VARCHAR(3),                   -- ISO 4217, e.g. 'JPY'
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

-- A stamp on one person's country page. Everyone at the meal has their own stamp
-- pointing at the same food_entry, with their own rating and notes.
CREATE TABLE stamp (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id      BIGINT   NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    food_entry_id BIGINT   NOT NULL REFERENCES food_entry (id),
    stamped_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    rating        INTEGER  CHECK (rating BETWEEN 1 AND 5),
    notes         VARCHAR(2000),
    CONSTRAINT stamp_one_per_person_per_entry UNIQUE (owner_id, food_entry_id)
);
CREATE INDEX stamp_owner_idx ON stamp (owner_id);

CREATE TABLE photo (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_entry_id  BIGINT       NOT NULL REFERENCES food_entry (id),
    uploaded_by_id BIGINT       REFERENCES app_user (id) ON DELETE SET NULL,
    storage_key    VARCHAR(300) NOT NULL UNIQUE,  -- where the bytes live in S3 / on disk
    content_type   VARCHAR(50)  NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
